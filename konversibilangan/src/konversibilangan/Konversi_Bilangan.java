    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        try{
            //konversi bilangan hexadecimal
            if(bilangan_dari.getSelectedItem()=="Hexadecimal"){
                //konversi bilngan hexa ke decimal
                if(bilangan_ke.getSelectedItem()=="Decimal"){
                    String hexa = inputdata.getText();
                    int outdec = Integer.parseInt(hexa,16);
                    outputdata.setText (Integer.toUnsignedString(outdec));
                }
                //konversi bilangan hexa ke biner
                else if (bilangan_ke.getSelectedItem()=="Biner"){
                    String hexa2 = inputdata.getText();
                    int outdec2 = Integer.parseInt (hexa2,16);
                    String hasilDec = Integer.toUnsignedString(outdec2);
                    int hasilBiner = Integer.parseInt (hasilDec);
                    outputdata.setText(Integer.toBinaryString(hasilBiner));
                }
                //konversi hexadecimal ke octal
                else if (bilangan_ke.getSelectedItem()=="Octal"){
                    String hexa3 = inputdata.getText();
                    int outdec3 = Integer.parseInt (hexa3,16);
                    String hasilDec2 = Integer.toUnsignedString(outdec3);
                    int hasilOctal2 = Integer.parseInt (hasilDec2);
                    outputdata.setText(Integer.toBinaryString(hasilOctal2));
                }
            }
            //konversi bilangan Octal
            else if (bilangan_dari.getSelectedItem()=="Octal"){
                //konversi octal ke decimal
                if (bilangan_ke.getSelectedItem()=="Decimal"){
                    String octal = inputdata.getText ();
                    int outdec3 = Integer.parseInt(octal,8);
                    outputdata.setText(Integer.toUnsignedString(outdec3));
                }
                //konversi octal ke biner
                else if (bilangan_ke.getSelectedItem()=="Biner"){
                    String octal2 = inputdata.getText();
                    int outdec4 = Integer.parseInt(octal2,8);
                    String hasilDec2 = Integer.toUnsignedString(outdec4);
                    int hasilBiner2 = Integer.parseInt(hasilDec2);
                    outputdata.setText(Integer.toBinaryString(hasilBiner2));
                }
                //konversi octal ke hexadecimal
                else if (bilangan_ke.getSelectedItem()=="Hexadecimal"){
                    String hexa3 = inputdata.getText();
                    int outdec5 = Integer.parseInt(hexa3,8);
                    String hasilDec3 = Integer.toUnsignedString(outdec5);
                    int hasilHexa3 = Integer.parseInt(hasilDec3);
                    outputdata.setText(Integer.toHexString(hasilHexa3));
                }
            }
            //konversi bilangan biner
            else if (bilangan_dari.getSelectedItem()=="Biner"){
                //konversi biner ke decimal
                if(bilangan_ke.getSelectedItem()=="Decimal"){
                    String biner4 = inputdata.getText();
                    int outdec6 = Integer.parseInt(biner4,2);
                    outputdata.setText(Integer.toUnsignedString(outdec6));
                }
                //konversi biner ke octal
                else if (bilangan_ke.getSelectedItem()=="Octal"){
                    String biner7 = inputdata.getText ();
                    int outdec7 = Integer.parseInt(biner7,2);
                    String hasilBiner7 = Integer.toUnsignedString(outdec7);
                    int hasilOctal7 = Integer.parseInt(hasilBiner7);
                    outputdata.setText(Integer.toOctalString(hasilOctal7));
                }
                //konversi biner ke hexadecimal
                else if (bilangan_ke.getSelectedItem()=="Hexadecimal"){
                    String biner8 = inputdata.getText();
                    int outdec8 = Integer.parseInt(biner8,2);
                    String hasilBiner8 = Integer.toUnsignedString(outdec8);
                    int hasilHexa8 = Integer.parseInt(hasilBiner8);
                    outputdata.setText(Integer.toHexString(hasilHexa8));
                }
            }
            //konversi bilangan decimal
            else if (bilangan_dari.getSelectedItem()=="Decimal"){
                //konverdi decimal ke octal
                if (bilangan_ke.getSelectedItem()=="Octal"){
                    String dec1 = inputdata.getText();
                    int outOctal9 = Integer.parseInt(dec1);
                    outputdata.setText(Integer.toOctalString(outOctal9));
                }
                //konversi decimal ke biner
                else if (bilangan_ke.getSelectedItem()=="Biner"){
                    String dec2 = inputdata.getText();
                    int outBiner9 = Integer.parseInt(dec2);
                    outputdata.setText(Integer.toBinaryString(outBiner9));
                }
                //konversi decimal ke hexadecimal
                else if (bilangan_ke.getSelectedItem()=="Biner"){
                    String dec3 = inputdata.getText();
                    int outHexa9 = Integer.parseInt(dec3);
                    outputdata.setText(Integer.toHexString(outHexa9));
                }
            }
        }catch(NumberFormatException ex){
            JOptionPane.showMessageDialog(null,"Input Tidak Benar");
        }
    }//GEN-LAST:event_jButton1ActionPerformed

